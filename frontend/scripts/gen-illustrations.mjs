// Copies the illustrations we use out of Microsoft's Fluent Emoji (MIT) into
// src/lib/illustrations.generated.ts, so the app ships ~60 small SVGs instead
// of the whole 3,000-icon set: the flat (full-color) style for NAMES, and the
// single-color high-contrast style for MONO_NAMES, which draws in the current
// text color. Run `npm run gen:illustrations` after adding a name to either list.
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const flat = require("@iconify-json/fluent-emoji-flat/icons.json");
const mono = require("@iconify-json/fluent-emoji-high-contrast/icons.json");

const NAMES = [
  // Ingredients
  "avocado", "bacon", "bell-pepper", "bread", "broccoli", "butter", "canned-food",
  "carrot", "cheese-wedge", "cooked-rice", "cucumber", "cut-of-meat", "ear-of-corn",
  "egg", "fish", "garlic", "glass-of-milk", "herb", "honey-pot", "hot-pepper",
  "leafy-green", "lemon", "mushroom", "olive", "onion", "potato", "poultry-leg",
  "salt", "shrimp", "spaghetti", "tomato",
  // Kitchen and steps
  "bowl-with-spoon", "cooking", "droplet", "fire", "fork-and-knife-with-plate",
  "kitchen-knife", "pot-of-food", "shallow-pan-of-food", "soap", "spoon",
  "thermometer", "timer-clock",
  // Flow and feedback
  "check-mark-button", "money-bag", "party-popper", "shopping-cart", "sparkles",
  "clapper-board", "round-pushpin", "magnifying-glass-tilted-left",
];

// Single-color icons, used where a set of icons should share one color: the
// "how it works" row on the home page and everything on the recipe steps.
// Ingredient pictures stay full color, since food is easier to recognize in color.
const MONO_NAMES = [
  // Home page
  "clapper-board", "shopping-cart", "money-bag", "cooking",
  // Recipe steps (see STEP_RULES in src/lib/illustrations.ts)
  "droplet", "fondue", "shallow-pan-of-food", "fire", "kitchen-knife",
  "bowl-with-spoon", "fork-and-knife-with-plate",
  // Recipe extraction progress (STAGE_PICTURES in src/components/JobProgress.tsx)
  "page-facing-up", "speaker-high-volume", "eyes",
  // Step callouts, timers, and the finished screen
  "magnifying-glass-tilted-left", "thermometer", "spoon", "timer-clock",
  "check-mark-button", "party-popper",
  // Results page headings and messages
  "sparkles",
];

function pick({ icons, aliases = {} }, names) {
  const out = {};
  for (const name of names) {
    const icon = icons[name] ?? icons[aliases[name]?.parent];
    if (!icon) throw new Error(`Unknown Fluent Emoji name: ${name}`);
    out[name] = icon.body;
  }
  return out;
}
const out = pick(flat, NAMES);
const outMono = pick(mono, MONO_NAMES);

const banner = `// Generated by scripts/gen-illustrations.mjs. Don't edit by hand.
// Fluent Emoji (flat and high contrast) © Microsoft Corporation, MIT License:
// https://github.com/microsoft/fluentui-emoji/blob/main/LICENSE
`;
const body = `export const ILLUSTRATIONS = ${JSON.stringify(out, null, 2)} as const;

export type IllustrationName = keyof typeof ILLUSTRATIONS;

export const ILLUSTRATIONS_MONO = ${JSON.stringify(outMono, null, 2)} as const;

export type MonoIllustrationName = keyof typeof ILLUSTRATIONS_MONO;
`;
writeFileSync(new URL("../src/lib/illustrations.generated.ts", import.meta.url), banner + body);
console.log(`Wrote ${NAMES.length} illustrations and ${MONO_NAMES.length} single-color icons`);
